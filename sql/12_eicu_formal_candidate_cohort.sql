CREATE TEMP TABLE _events AS

SELECT i.patientunitstayid AS stay_id,p.hospitalid,m.drug,i.infusionoffset AS t,

       MAX(TRIM(i.drugrate)::numeric)::double precision AS rate,

       MAX(i.drugname) AS raw_name

FROM infusiondrug i

JOIN _drug_map m ON m.raw_name=i.drugname

JOIN patient p USING(patientunitstayid)

WHERE TRIM(i.drugrate) ~ '^-?[0-9]+(\.[0-9]+)?$'

  AND TRIM(i.drugrate)::numeric > 0

GROUP BY i.patientunitstayid,p.hospitalid,m.drug,i.infusionoffset;

CREATE INDEX _events_stay_drug_time_idx ON _events(stay_id,drug,t);


CREATE TEMP TABLE _target_times AS

SELECT stay_id,MAX(hospitalid) AS hospitalid,

       MIN(t) FILTER (WHERE drug='dexmedetomidine') AS dex_t,

       MIN(t) FILTER (WHERE drug='midazolam') AS mid_t

FROM _events

GROUP BY stay_id;


CREATE TEMP TABLE _hospital_support AS

SELECT hospitalid,

       COUNT(DISTINCT stay_id) FILTER (WHERE drug='dexmedetomidine') AS dex_stays,

       COUNT(DISTINCT stay_id) FILTER (WHERE drug='midazolam') AS mid_stays

FROM _events

GROUP BY hospitalid;


CREATE TEMP TABLE _candidate AS

SELECT p.uniquepid,p.patienthealthsystemstayid,p.patientunitstayid AS stay_id,p.hospitalid,

       p.gender,p.age,p.unitvisitnumber,p.unittype,p.unitadmitsource,p.unitstaytype,

       p.unitdischargeoffset,p.hospitaldischargeoffset,p.unitdischargestatus,p.hospitaldischargestatus,

       LEAST(t.dex_t,t.mid_t) AS t0,

       CASE WHEN t.dex_t=t.mid_t THEN 'TIE'

            WHEN t.dex_t IS NOT NULL AND (t.mid_t IS NULL OR t.dex_t<t.mid_t) THEN 'DEX'

            WHEN t.mid_t IS NOT NULL AND (t.dex_t IS NULL OR t.mid_t<t.dex_t) THEN 'MIDAZ' END AS treatment,

       hs.dex_stays AS hospital_dex_stays,hs.mid_stays AS hospital_midaz_stays

FROM _target_times t

JOIN patient p ON p.patientunitstayid=t.stay_id

JOIN _hospital_support hs ON hs.hospitalid=p.hospitalid

WHERE (CASE WHEN p.age='> 89' THEN 90 WHEN TRIM(p.age) ~ '^[0-9]+$' THEN p.age::int END) >=18

  AND LEAST(t.dex_t,t.mid_t) >=0

  AND LEAST(t.dex_t,t.mid_t) <=p.unitdischargeoffset;

CREATE INDEX _candidate_stay_idx ON _candidate(stay_id);


CREATE TEMP TABLE _prop_summary AS

SELECT c.stay_id,

       COUNT(*) FILTER (WHERE e.t>=c.t0-180 AND e.t<c.t0) AS prop_records_3h,

       COUNT(*) FILTER (WHERE e.t>=c.t0-360 AND e.t<c.t0) AS prop_records_6h,

       COUNT(*) FILTER (WHERE e.t>=c.t0-720 AND e.t<c.t0) AS prop_records_12h,

       MAX(e.t) FILTER (WHERE e.t<c.t0) AS last_prop_t,

       (ARRAY_AGG(e.rate ORDER BY e.t DESC) FILTER (WHERE e.t<c.t0))[1] AS last_prop_rate_12h,

       (ARRAY_AGG(e.raw_name ORDER BY e.t DESC) FILTER (WHERE e.t<c.t0))[1] AS last_prop_raw_name_12h

FROM _candidate c

LEFT JOIN _events e ON e.stay_id=c.stay_id AND e.drug='propofol'

  AND e.t<c.t0 AND e.t>=c.t0-720

GROUP BY c.stay_id;


CREATE TEMP TABLE _mv_summary AS

SELECT c.stay_id,

       BOOL_OR(c.t0 BETWEEN r.ventstartoffset AND r.ventendoffset

               AND COALESCE(r.airwaytype,'')<>'No Artificial Airway') AS invasive_mv_at_t0,

       MIN(r.ventendoffset) FILTER (WHERE c.t0 BETWEEN r.ventstartoffset AND r.ventendoffset

               AND COALESCE(r.airwaytype,'')<>'No Artificial Airway') AS current_mv_end

FROM _candidate c

LEFT JOIN respiratorycare r ON r.patientunitstayid=c.stay_id

GROUP BY c.stay_id;


CREATE TEMP TABLE _sedation AS

SELECT n.patientunitstayid AS stay_id,n.nursingchartoffset AS t,

       MAX(n.nursingchartvalue) FILTER (WHERE n.nursingchartcelltypevalname='Sedation Scale') AS scale,

       MAX(TRIM(n.nursingchartvalue)::numeric) FILTER (

           WHERE n.nursingchartcelltypevalname='Sedation Score'

             AND TRIM(n.nursingchartvalue) ~ '^-?[0-9]+(\.[0-9]+)?$')::double precision AS score

FROM nursecharting n

JOIN _candidate c ON c.stay_id=n.patientunitstayid

WHERE n.nursingchartcelltypevalname IN ('Sedation Scale','Sedation Score')

  AND n.nursingchartoffset BETWEEN c.t0-360 AND c.t0

GROUP BY n.patientunitstayid,n.nursingchartoffset;

CREATE INDEX _sedation_stay_time_idx ON _sedation(stay_id,t);


CREATE TEMP TABLE _sed_summary AS

SELECT c.stay_id,

       COUNT(*) FILTER (WHERE s.t>=c.t0-240 AND s.scale IN ('RASS','SAS') AND s.score IS NOT NULL) AS sedation_n_4h,

       COUNT(*) FILTER (WHERE s.scale IN ('RASS','SAS') AND s.score IS NOT NULL) AS sedation_n_6h,

       (ARRAY_AGG(s.scale ORDER BY s.t DESC) FILTER (WHERE s.t>=c.t0-240 AND s.scale IN ('RASS','SAS') AND s.score IS NOT NULL))[1] AS sedation_scale_4h,

       (ARRAY_AGG(s.score ORDER BY s.t DESC) FILTER (WHERE s.t>=c.t0-240 AND s.scale IN ('RASS','SAS') AND s.score IS NOT NULL))[1] AS sedation_score_4h,

       (ARRAY_AGG(s.scale ORDER BY s.t DESC) FILTER (WHERE s.scale IN ('RASS','SAS') AND s.score IS NOT NULL))[1] AS sedation_scale_6h,

       (ARRAY_AGG(s.score ORDER BY s.t DESC) FILTER (WHERE s.scale IN ('RASS','SAS') AND s.score IS NOT NULL))[1] AS sedation_score_6h,

       MAX(s.t) FILTER (WHERE s.scale IN ('RASS','SAS') AND s.score IS NOT NULL) AS sedation_t_6h

FROM _candidate c

LEFT JOIN _sedation s USING(stay_id)

GROUP BY c.stay_id;


CREATE TEMP TABLE _gcs_summary AS

SELECT c.stay_id,

       (ARRAY_AGG(TRIM(n.nursingchartvalue)::numeric ORDER BY n.nursingchartoffset DESC)

        FILTER (WHERE TRIM(n.nursingchartvalue) ~ '^[0-9]+(\.[0-9]+)?$'))[1]::double precision AS gcs_6h

FROM _candidate c

LEFT JOIN nursecharting n ON n.patientunitstayid=c.stay_id

  AND n.nursingchartcelltypevalname='GCS Total'

  AND n.nursingchartoffset BETWEEN c.t0-360 AND c.t0

GROUP BY c.stay_id;


CREATE TEMP TABLE _cointervention AS

SELECT c.stay_id,

       BOOL_OR(e.drug='cisatracurium') AS cisatracurium_6h,

       BOOL_OR(e.drug='fentanyl') AS fentanyl_6h,

       BOOL_OR(e.drug IN ('norepinephrine','phenylephrine','vasopressin','epinephrine','dopamine')) AS vasopressor_6h

FROM _candidate c

LEFT JOIN _events e ON e.stay_id=c.stay_id AND e.t BETWEEN c.t0-360 AND c.t0

GROUP BY c.stay_id;


