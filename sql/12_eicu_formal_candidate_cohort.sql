       CASE WHEN ps.last_prop_t IS NOT NULL THEN (c.t0-ps.last_prop_t)::double precision/60.0 END AS hours_since_last_prop_start,

       ''::text AS hours_since_last_prop_end,

       CASE WHEN ps.last_prop_raw_name_12h ILIKE '%mcg/kg/min%' THEN ps.last_prop_rate_12h END AS prop_rate_direct_at_t0,

       CASE WHEN ps.last_prop_raw_name_12h ILIKE '%mcg/kg/min%' THEN 1 ELSE 0 END AS prop_direct_segments_at_t0,

       COALESCE(mv.invasive_mv_at_t0,false)::int AS invasive_mv_at_t0,

       CASE WHEN mv.current_mv_end IS NOT NULL THEN (mv.current_mv_end-c.t0)::double precision/60.0 END AS hours_to_current_mv_end,

       ss.sedation_n_4h,ss.sedation_n_6h,ss.sedation_scale_4h,ss.sedation_score_4h,

       ss.sedation_scale_6h,ss.sedation_score_6h,

       CASE WHEN ss.sedation_t_6h IS NOT NULL THEN (c.t0-ss.sedation_t_6h)::double precision/60.0 END AS hours_since_sedation_6h,

       gs.gcs_6h,COALESCE(ci.cisatracurium_6h,false)::int AS cisatracurium_6h,

       COALESCE(ci.fentanyl_6h,false)::int AS fentanyl_6h,

       COALESCE(ci.vasopressor_6h,false)::int AS vasopressor_6h,

       CASE WHEN LOWER(c.hospitaldischargestatus)='expired' THEN 1

            WHEN LOWER(c.hospitaldischargestatus)='alive' THEN 0 END AS hospital_mortality,

       c.unitdischargeoffset::double precision/1440.0 AS los_icu,

       c.hospitaldischargeoffset::double precision/1440.0 AS los_hospital,

       c.hospital_dex_stays,c.hospital_midaz_stays

FROM _candidate c

LEFT JOIN _prop_summary ps USING(stay_id)

LEFT JOIN _mv_summary mv USING(stay_id)

LEFT JOIN _sed_summary ss USING(stay_id)

LEFT JOIN _gcs_summary gs USING(stay_id)

LEFT JOIN _cointervention ci USING(stay_id)

ORDER BY c.stay_id;

